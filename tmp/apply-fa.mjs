import fs from "node:fs";
import pg from "pg";
import { config } from "dotenv";
config({quiet:true});
const c = new pg.Client({connectionString: process.env.DATABASE_URL.replace(/\/[^/]+$/, "/erp_system1_test")});
await c.connect();
await c.query(fs.readFileSync("migrations/2026-10-20-fixed-assets.sql","utf8"));
const t = await c.query("select count(*)::int n from fixed_assets");
console.log("fixed_assets ready, rows:", t.rows[0].n);
await c.end();
